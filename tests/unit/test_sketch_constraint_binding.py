class TestBindSketchConstraint:
    """Binding sketch dimensions with spreadsheet_bind_property."""

    async def test_plain_property_still_binds(
        self, spreadsheet_tools: RegisteredTools, pad: StandInPad
    ) -> None:
        """A plain property such as Pad.Length binds as before."""
        result = await spreadsheet_tools["spreadsheet_bind_property"](
            "Params", "Height", "Pad", "Length"
        )
        assert result["target_property"] == "Length"
        assert pad.expressions == {"Length": "Params.Height"}

    async def test_binds_constraint_by_index(
        self, spreadsheet_tools: RegisteredTools, sketch: StandInSketch
    ) -> None:
        """Constraints[N] binds a dimensional constraint by index."""
        result = await spreadsheet_tools["spreadsheet_bind_property"](
            "Params", "Width", "Sketch", "Constraints[9]"
        )
        assert result["target_property"] == "Constraints[9]"
        assert sketch.expressions == {"Constraints[9]": "Params.Width"}

    @pytest.mark.parametrize("path", ["Constraints.Length", ".Constraints.Length"])
    async def test_binds_constraint_by_name(
        self,
        spreadsheet_tools: RegisteredTools,
        sketch: StandInSketch,
        path: str,
    ) -> None:
        """Constraints.Name binds a named constraint, with or without a dot."""
        result = await spreadsheet_tools["spreadsheet_bind_property"](
            "Params", "Length", "Sketch", path
        )
        assert result["target_property"] == "Constraints.Length"
        assert sketch.expressions == {"Constraints.Length": "Params.Length"}

    @pytest.mark.parametrize(
        ("path", "message"),
        [
            ("Constraints[99]", "out of range"),
            ("Constraints.Nope", "No constraint named"),
            ("Constraints[0]", "Coincident constraint"),
            ("Constraints[10]", "reference"),
        ],
    )
    async def test_rejects_unusable_constraints(
        self,
        spreadsheet_tools: RegisteredTools,
        sketch: StandInSketch,
        path: str,
        message: str,
    ) -> None:
        """Missing, geometric and reference constraints give clear errors."""
        with pytest.raises(ValueError, match=message):
            await spreadsheet_tools["spreadsheet_bind_property"](
                "Params", "Width", "Sketch", path
            )
        assert sketch.expressions == {}

    async def test_rejects_constraint_path_on_non_sketch(
        self, spreadsheet_tools: RegisteredTools
    ) -> None:
        """A constraint path on an object that is not a sketch is rejected."""
        with pytest.raises(ValueError, match="not a sketch"):
            await spreadsheet_tools["spreadsheet_bind_property"](
                "Params", "Width", "Pad", "Constraints[0]"
            )

    async def test_unknown_plain_property_still_rejected(
        self, spreadsheet_tools: RegisteredTools
    ) -> None:
        """A property the object does not have is still rejected."""
        with pytest.raises(ValueError, match="Property not found"):
            await spreadsheet_tools["spreadsheet_bind_property"](
                "Params", "Width", "Pad", "Nope"
            )


class TestNamedConstraints:
    """Naming constraints with add_sketch_constraint."""

    async def test_adds_named_constraint(
        self, partdesign_tools: RegisteredTools, sketch: StandInSketch
    ) -> None:
        """A name given to add_sketch_constraint is applied to the constraint."""
        result = await partdesign_tools["add_sketch_constraint"](
            "Sketch", "DistanceY", 1, value=25.0, name="Width"
        )
        assert result["name"] == "Width"
        assert sketch.Constraints[result["constraint_index"]].Name == "Width"

    async def test_unnamed_constraint_reports_none(
        self, partdesign_tools: RegisteredTools
    ) -> None:
        """Without a name the result reports None."""
        result = await partdesign_tools["add_sketch_constraint"](
            "Sketch", "DistanceY", 1, value=25.0
        )
        assert result["name"] is None

    async def test_rejects_duplicate_name(
        self, partdesign_tools: RegisteredTools, sketch: StandInSketch
    ) -> None:
        """A name already used in the sketch is rejected before adding."""
        count = sketch.ConstraintCount
        with pytest.raises(ValueError, match="already used"):
            await partdesign_tools["add_sketch_constraint"](
                "Sketch", "DistanceY", 1, value=25.0, name="Length"
            )
        assert sketch.ConstraintCount == count

    @pytest.mark.parametrize("name", ["9lives", "has space", "dash-name", ""])
    async def test_rejects_invalid_name(
        self, partdesign_tools: RegisteredTools, name: str
    ) -> None:
        """Names that cannot appear in an expression path are rejected."""
        with pytest.raises(ValueError, match="Invalid constraint name"):
            await partdesign_tools["add_sketch_constraint"](
                "Sketch", "DistanceY", 1, value=25.0, name=name
            )


@pytest.mark.parametrize(
    ("name", "valid"),
    [("Width", True), ("_x1", True), ("1x", False), ("a.b", False)],
)
def test_is_valid_constraint_name(name: str, valid: bool) -> None:
    """Constraint names follow expression identifier rules."""
    assert _is_valid_constraint_name(name) is valid

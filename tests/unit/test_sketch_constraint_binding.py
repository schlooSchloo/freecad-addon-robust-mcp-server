"""Unit tests for binding sketch dimensions to spreadsheet aliases.

These tests run the FreeCAD-side Python generated by the tools against small
stand-in objects, so the validation logic in that generated code is exercised
without a running FreeCAD instance.
"""

import sys
from collections.abc import Awaitable, Callable
from dataclasses import dataclass, field
from typing import Any
from unittest.mock import AsyncMock, MagicMock

import pytest

from freecad_mcp.bridge.base import ExecutionResult
from freecad_mcp.tools.partdesign import (
    _is_valid_constraint_name,
    register_partdesign_tools,
)
from freecad_mcp.tools.spreadsheet import register_spreadsheet_tools

RegisteredTools = dict[str, Callable[..., Awaitable[Any]]]


@dataclass
class StandInConstraint:
    """Stand-in for a Sketcher constraint."""

    Type: str
    Name: str = ""
    Driving: bool = True


@dataclass
class StandInSketch:
    """Stand-in for a Sketcher::SketchObject with expression support."""

    Name: str
    Constraints: list[StandInConstraint] = field(default_factory=list)
    expressions: dict[str, str] = field(default_factory=dict)

    @property
    def ConstraintCount(self) -> int:
        """Return the number of constraints."""
        return len(self.Constraints)

    def renameConstraint(self, index: int, name: str) -> None:
        """Rename the constraint at an index."""
        self.Constraints[index].Name = name

    def addConstraint(self, constraint: StandInConstraint) -> int:
        """Append a constraint and return its index."""
        self.Constraints.append(constraint)
        return len(self.Constraints) - 1

    def setExpression(self, path: str, expression: str) -> None:
        """Record an expression binding."""
        self.expressions[path] = expression


@dataclass
class StandInPad:
    """Stand-in for an object with a plain Length property."""

    Name: str
    Length: float = 10.0
    expressions: dict[str, str] = field(default_factory=dict)

    def setExpression(self, path: str, expression: str) -> None:
        """Record an expression binding."""
        self.expressions[path] = expression


class StandInSheet:
    """Stand-in for a Spreadsheet::Sheet with one alias per cell."""

    def __init__(self, name: str, aliases: dict[str, str]) -> None:
        """Create a sheet with alias -> cell mappings."""
        self.Name = name
        self._aliases = aliases

    def getCellFromAlias(self, alias: str) -> str | None:
        """Return the cell for an alias, or None."""
        return self._aliases.get(alias)


class StandInDocument:
    """Stand-in for a FreeCAD document."""

    def __init__(self, objects: list[Any]) -> None:
        """Create a document holding the given objects."""
        self._objects = {obj.Name: obj for obj in objects}
        self.transactions: list[str] = []

    def getObject(self, name: str) -> Any:
        """Return an object by name, or None."""
        return self._objects.get(name)

    def openTransaction(self, name: str) -> None:
        """Record an opened transaction."""
        self.transactions.append(f"open:{name}")

    def commitTransaction(self) -> None:
        """Record a committed transaction."""
        self.transactions.append("commit")

    def abortTransaction(self) -> None:
        """Record an aborted transaction."""
        self.transactions.append("abort")

    def recompute(self) -> None:
        """Do nothing; recompute is not modelled."""


def _make_sketch() -> StandInSketch:
    """Build a rectangle-like sketch: 8 geometric + 2 dimensional constraints."""
    constraints = [StandInConstraint("Coincident") for _ in range(4)]
    constraints += [StandInConstraint("Horizontal"), StandInConstraint("Vertical")]
    constraints += [StandInConstraint("Horizontal"), StandInConstraint("Vertical")]
    constraints.append(StandInConstraint("DistanceX", Name="Length"))
    constraints.append(StandInConstraint("DistanceY"))
    constraints.append(StandInConstraint("Distance", Driving=False))
    return StandInSketch("Sketch", constraints)


class _BridgeRunningCode:
    """Bridge stand-in that runs generated code against stand-in objects."""

    def __init__(self, document: StandInDocument) -> None:
        """Hold the document the generated code should see."""
        self.document = document
        self.freecad = MagicMock()
        self.freecad.ActiveDocument = document
        self.freecad.getDocument = MagicMock(return_value=document)

    async def execute_python(self, code: str) -> ExecutionResult:
        """Execute generated code and report the result like the real bridge."""
        namespace: dict[str, Any] = {"FreeCAD": self.freecad, "App": self.freecad}
        sketcher = MagicMock()
        sketcher.Constraint = lambda ctype, *_args: StandInConstraint(ctype)
        try:
            sys.modules["Sketcher"] = sketcher
            exec(code, namespace)  # noqa: S102 - testing generated FreeCAD code
        except Exception as error:
            return ExecutionResult(
                success=False,
                result=None,
                stdout="",
                stderr="",
                execution_time_ms=1.0,
                error_type=type(error).__name__,
                error_traceback=str(error),
            )
        finally:
            sys.modules.pop("Sketcher", None)
        return ExecutionResult(
            success=True,
            result=namespace.get("_result_"),
            stdout="",
            stderr="",
            execution_time_ms=1.0,
        )


def _capture_tools(register: Callable[..., None], bridge: Any) -> RegisteredTools:
    """Register tools on a stand-in MCP server and return them by name."""
    mcp = MagicMock()
    tools: RegisteredTools = {}

    def tool_decorator(*_args: Any, **_kwargs: Any) -> Callable[..., Any]:
        def wrapper(func: Callable[..., Awaitable[Any]]) -> Any:
            tools[func.__name__] = func
            return func

        return wrapper

    mcp.tool = tool_decorator
    register(mcp, AsyncMock(return_value=bridge))
    return tools


